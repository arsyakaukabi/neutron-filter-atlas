"""Generate the column dictionary (wiki/atlas-columns.md, results-tables.md, curated-tables.md) from columns.yaml and
the headers of the released tables.

Fails if a table has a column that columns.yaml does not describe, or if columns.yaml describes a column the table
does not have. Ranges and allowed values are read from the data, so the released data must be in place (data/ or
FA_DATA).
Usage: python tools/docs/gen_columns.py          (write the two pages)
       python tools/docs/gen_columns.py --check  (exit 1 if the pages on disk differ from a fresh generation)
"""
import os
import sys
from pathlib import Path

import pandas as pd
import yaml

REPO = Path(__file__).resolve().parents[2]
DATA = Path(os.environ.get("FA_DATA", REPO / "data"))
SPEC = REPO / "tools" / "docs" / "columns.yaml"
WIKI = REPO / "wiki"
MAX_LISTED = 12   # text columns with at most this many distinct values list them all ...
MAX_VALUE_LEN = 40   # ... if every value is a short code

HEAD_ATLAS = """# Atlas columns

What this page is for: the meaning, unit and definition of every column of the atlas table.
Who should read it: anyone who reads `atlas.parquet`; start here before comparing numbers.

Generated by `tools/docs/gen_columns.py` from `tools/docs/columns.yaml` and the file header; edit the YAML, not this
page. The other released tables are described in [Results tables](results-tables.md); the definitions behind the
columns are in [Concepts](concepts.md).

How to read the table below: **Range / values** is read from the released file (numbers: minimum and maximum over all
rows; text: the allowed values). An empty cell in the data is a missing value, and the last column says what it means.
"−ln T" marks a rejection: the negative natural logarithm of a transmission, so 1 means a factor e and 2.3 a factor 10.
"""

HEAD_RESULTS = """# Results tables

What this page is for: the columns of every released table other than the atlas.
Who should read it: users who go beyond the atlas (validation, fronts, coverage, shortlist) and pipeline users.

Generated by `tools/docs/gen_columns.py` from `tools/docs/columns.yaml` and the file headers; edit the YAML, not this
page. The atlas table itself is in [Atlas columns](atlas-columns.md). The JSON result files are listed in
[Data](data.md#what-the-results-archive-holds); the hand-made tables kept in the repository are in
[Curated tables](curated-tables.md).
"""

HEAD_CURATED = """# Curated tables

What this page is for: the columns of the hand-made tables in `data/curated/`, which are tracked in git.
Who should read it: users who want to know where the commercially grown crystals, the water-sensitive families, the
extra EXFOR entries and the practicality data come from, or who want to extend them.

Generated by `tools/docs/gen_columns.py` from `tools/docs/columns.yaml` and the file headers; edit the YAML, not this
page. Each table has a short README next to it where one exists (`growable_crystals_README.md`,
`stage4_dossier_README.md`).
"""


def load(path):
    return pd.read_parquet(path) if path.suffix == ".parquet" else pd.read_csv(path)


def fmt(x):
    if isinstance(x, float):
        if x != x:
            return "nan"
        if x in (float("inf"), float("-inf")):
            return "inf" if x > 0 else "-inf"
        return f"{x:.6g}"
    return str(x)


def values(s):
    s = s.dropna()
    if s.empty:
        return "all missing"
    if s.dtype.kind == "b" or set(map(str, s.unique())) <= {"True", "False"}:
        return ", ".join(sorted({str(v).lower() for v in s.unique()}))
    if s.dtype.kind in "fiu":
        return f"{fmt(s.min())} to {fmt(s.max())}"
    u = sorted({str(v) for v in s.unique()})
    if len(u) <= MAX_LISTED and max(map(len, u)) <= MAX_VALUE_LEN:   # short codes only; free text is summarised
        return ", ".join(f"`{v}`" if v else "(empty string)" for v in u)
    return f"text, {len(u)} distinct values"


def cell(t):
    return str(t).replace("|", "\\|").replace("\n", " ")


def table_md(t):
    path = DATA / t["file"]
    df = load(path)
    spec = t["columns"]
    undocumented = [c for c in df.columns if c not in spec]
    absent = [c for c in spec if c not in df.columns]
    if undocumented or absent:
        raise SystemExit(f"{t['file']}: undocumented columns {undocumented}; described but absent {absent}")
    out = [f"## {t['title']}", "", f"File: `data/{t['file']}`. {len(df):,} rows: {t['row']}.", "",
           "| Column | Meaning | Unit | How it is computed | Range / values | Missing value |",
           "|---|---|---|---|---|---|"]
    for c in df.columns:
        fields = [f.strip() for f in spec[c].split(" | ")]
        if len(fields) != 4:
            raise SystemExit(f"{t['file']} {c}: expected 4 fields separated by ' | ', got {len(fields)}")
        meaning, unit, how, na = fields
        out.append(f"| `{c}` | {cell(meaning)} | {cell(unit)} | {cell(how)} | {cell(values(df[c]))} | {cell(na)} |")
    return out + [""]


def render():
    spec = yaml.safe_load(SPEC.read_text(encoding="utf-8"))["tables"]
    atlas = [t for t in spec if t["file"] == "derived/atlas.parquet"]
    rest = [t for t in spec if t["file"].startswith("derived/") and t["file"] != "derived/atlas.parquet"]
    cur = [t for t in spec if t["file"].startswith("curated/")]
    a = HEAD_ATLAS.splitlines() + [""]
    for t in atlas:
        a += table_md(t)
    r = HEAD_RESULTS.splitlines() + ["", "Contents:", ""]
    r += [f"- [{t['title']}](#{anchor(t['title'])})" for t in rest] + [""]
    for t in rest:
        r += table_md(t)
    c = HEAD_CURATED.splitlines() + [""]
    for t in cur:
        c += table_md(t)
    return {"atlas-columns.md": "\n".join(a).rstrip() + "\n", "results-tables.md": "\n".join(r).rstrip() + "\n",
            "curated-tables.md": "\n".join(c).rstrip() + "\n"}


def anchor(title):
    s = "".join(ch for ch in title.lower() if ch.isalnum() or ch in " -")
    return s.replace(" ", "-")


def main():
    pages = render()
    if "--check" in sys.argv:
        stale = [n for n, txt in pages.items() if not (WIKI / n).exists()
                 or (WIKI / n).read_text(encoding="utf-8") != txt]
        print("up to date" if not stale else f"stale: {stale}")
        sys.exit(1 if stale else 0)
    WIKI.mkdir(exist_ok=True)
    for n, txt in pages.items():
        (WIKI / n).write_bytes(txt.encode("utf-8"))
        print(f"wrote wiki/{n} ({txt.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
