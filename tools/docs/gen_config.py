"""Generate wiki/configuration.md from configs/*.yaml and the code that reads them.

For every key (top level and one level below) the page lists the value in the repository (the default), its type, the
comment next to it in the YAML file (or the text in tools/docs/config_notes.yaml where that file overrides it), the
modules that read it and the pipeline steps that reach those modules. Readers are found in the source: a module reads
a key if it loads the file with cfg("<file>") and names the key as a string; keys read in
filteratlas/common/constants.py are followed to the modules that import the constant.
Usage: python tools/docs/gen_config.py          (write the page)
       python tools/docs/gen_config.py --check  (exit 1 if the page on disk differs from a fresh generation)
"""
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))
from filteratlas.common.config import cfg  # noqa: E402

SRC = REPO / "src" / "filteratlas"
NOTES = yaml.safe_load((REPO / "tools" / "docs" / "config_notes.yaml").read_text(encoding="utf-8"))
OUT = REPO / "wiki" / "configuration.md"
KEY_RX = re.compile(r"^(\s*)([A-Za-z0-9_\".\- ]+?):(?:\s+(.*?))?\s*$")

HEAD = """# Configuration

What this page is for: every key of the configuration files in `configs/`, its value, what it controls and which
pipeline step reads it.
Who should read it: pipeline users who want to change a band, a temperature, a threshold or a compute setting.

Generated by `tools/docs/gen_config.py` from the YAML files and the source code; edit the YAML comments or
`tools/docs/config_notes.yaml`, not this page. **Value** is the value in the repository, which is the value behind the
released atlas. **Read by** lists the modules that read the key and, in brackets, the pipeline steps (`pipelines/NN_*.py`)
that import those modules directly or one level down. Readers are found by a text search for the key in modules
that load the file, so a module that reads a key of the same name from another section can appear too. Keys one level down are written `parent.child`; deeper structures are described at their
parent. How to change a value safely is in [Extending](extending.md); data paths (`paths.yaml`) are explained in
[Data](data.md#where-the-files-go).

Changing a value changes the results only after the steps that read it are rerun, and every later step that reads
their outputs. Values marked as fixed before the computation define the published atlas; change them for your own
studies, not to reproduce the release.
"""


def module_name(p):
    return ".".join(p.relative_to(REPO / "src").with_suffix("").parts)


def sources():
    return {module_name(p): p.read_text(encoding="utf-8") for p in SRC.rglob("*.py")}


def imports(text):
    """filteratlas modules imported by a source text (module and package-level imports)."""
    out = set()
    for m in re.finditer(r"^\s*from\s+(filteratlas[\w.]*)\s+import\s+(?:\(([^)]*)\)|([^\n#]*))", text, re.M):
        base = m.group(1)
        for part in (m.group(2) or m.group(3)).split(","):
            name = part.split(" as ")[0].strip()
            if name:
                out.add(f"{base}.{name}")
        out.add(base)
    for m in re.finditer(r"^\s*import\s+(filteratlas[\w.]*)", text, re.M):
        out.add(m.group(1))
    return out


def reach(start, src, depth=2):
    """Modules imported by a pipeline script (depth 1) and the modules those import (depth 2)."""
    seen, layer = set(), {m for m in start if m in src}
    for _ in range(depth):
        seen |= layer
        layer = {x for m in layer for x in imports(src[m]) if x in src} - seen
    return seen


def step_map(src):
    """module -> pipeline step labels (NN) whose entry script reaches it through imports."""
    out = {}
    for p in sorted((REPO / "pipelines").glob("[0-9][0-9]_*.py")):
        for m in reach(imports(p.read_text(encoding="utf-8")), src):
            out.setdefault(m, set()).add(p.name[:2])
    return out


def constants_map(src):
    """key -> constant names defined from it in common/constants.py (e.g. 'band_A' -> {'BAND'})."""
    out = {}
    for name, key in re.findall(r"^([A-Z_]+)\s*=.*?\[\"([\w.]+)\"\]", src["filteratlas.common.constants"], re.M):
        out.setdefault(key, set()).add(name)
    return out


def readers(fname, key, src, consts):
    rx_file = re.compile(r"cfg\(\s*[\"']" + re.escape(fname) + r"[\"']\s*\)")
    rx_key = re.compile(r"[\"']" + re.escape(key) + r"[\"']")
    mods = {m for m, t in src.items() if rx_file.search(t) and rx_key.search(t)}
    if "filteratlas.common.constants" in mods:
        mods.discard("filteratlas.common.constants")
        for c in consts.get(key, ()):
            mods |= {m for m, t in src.items() if re.search(r"\b" + c + r"\b", t) and m != "filteratlas.common.constants"}
    return sorted(mods)


def yaml_entries(path):
    """(dotted key, comment) for top-level keys and one level below, in file order."""
    out, stack = [], []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith(("#", "-")):
            continue
        body, _, comment = line.partition(" #")
        m = KEY_RX.match(body)
        if not m:
            continue
        ind = len(m.group(1))
        key = m.group(2).strip().strip('"')
        while stack and stack[-1][0] >= ind:
            stack.pop()
        # one level below the top, and only for setting names (not data entries such as formulas or EXFOR codes)
        if not stack or (len(stack) == 1 and re.fullmatch(r"[a-z][a-z0-9_]*", key)):
            dotted = ".".join([s[1] for s in stack] + [key])
            out.append((dotted, comment.strip()))
        stack.append((ind, key))
    return out


def value_of(data, dotted):
    v = data
    for k in dotted.split("."):
        v = v[k]
    return v


def show(v):
    if isinstance(v, dict):
        return f"mapping ({len(v)} entries)" if len(str(v)) > 60 else str(v).replace("'", "")
    if isinstance(v, list):
        s = str(v).replace("'", "")
        return s if len(s) <= 60 else f"list ({len(v)} entries)"
    return str(v)


def typ(v):
    if isinstance(v, bool):
        return "true/false"
    if isinstance(v, int):
        return "integer"
    if isinstance(v, float):
        return "number"
    if isinstance(v, str):
        return "text"
    if isinstance(v, list):
        return "list"
    return "mapping"


def cell(t):
    return str(t).replace("|", "\\|")


def render():
    src = sources()
    steps = step_map(src)
    consts = constants_map(src)
    lines = HEAD.splitlines() + ["", "Files: " + ", ".join(f"[`{p.stem}.yaml`](#{p.stem}yaml)" for p in
                                                        sorted((REPO / "configs").glob("*.yaml"))), ""]
    for path in sorted((REPO / "configs").glob("*.yaml")):
        name = path.stem
        data = cfg(name)
        first = path.read_text(encoding="utf-8").splitlines()[0].lstrip("# ").strip()
        lines += [f"## {name}.yaml", "", NOTES.get("files", {}).get(name, first), ""]
        if name == "paths":
            lines += ["`data_root` is the data directory relative to the repository (overridden by the environment "
                      "variable `FA_DATA`). `dirs` maps a short name to a directory under it and `files` maps a file "
                      "name to its path; the code asks for `D(\"name\")` and `F(\"name\")` "
                      "(`filteratlas.common.paths`). "
                      f"There are {len(data['dirs'])} directories and {len(data['files'])} files; see "
                      "[Data](data.md#where-the-files-go) for the layout.", ""]
            continue
        lines += ["| Key | Value | Type | Meaning | Read by |", "|---|---|---|---|---|"]
        for dotted, comment in yaml_entries(path):
            v = value_of(data, dotted)
            leaf = dotted.split(".")[-1]
            note = NOTES.get("keys", {}).get(f"{name}.{dotted}", comment) or "(see the parent key)"
            mods = readers(name, leaf, src, consts)
            if not mods and "." in dotted:   # nested keys are often read through their parent
                mods = readers(name, dotted.split(".")[0], src, consts)
            st = sorted({s for m in mods for s in steps.get(m, ())})
            who = ", ".join(f"`{m.replace('filteratlas.', '')}`" for m in mods) or "tests or documentation only"
            if st:
                who += f" ({', '.join(st)})"
            lines.append(f"| `{dotted}` | `{cell(show(v))}` | {typ(v)} | {cell(note)} | {who} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main():
    txt = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == txt
        print("up to date" if ok else "stale: configuration.md")
        sys.exit(0 if ok else 1)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_bytes(txt.encode("utf-8"))
    print(f"wrote wiki/configuration.md ({txt.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
